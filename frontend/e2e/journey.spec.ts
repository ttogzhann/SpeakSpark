import { test, expect } from '@playwright/test'

test('tutor browses, presents, saves, and creates speaking activities without an account', async ({ page, request }, testInfo) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Library', exact: true })).toBeVisible()
  await expect(page.getByRole('navigation').getByRole('link')).toHaveCount(4)
  await expect(page.getByLabel(/password|login|registration/i)).toHaveCount(0)

  const collection = await request.get('/api/activities?level=A1&type=Conversation+Cards')
  expect(collection.ok()).toBeTruthy()
  const matching = (await collection.json())[0]
  expect(matching).toBeTruthy()
  await page.getByRole('combobox', { name: 'Level', exact: true }).selectOption('A1')
  await page.getByRole('combobox', { name: 'Topic', exact: true }).selectOption(matching.topic)
  await page.getByRole('combobox', { name: 'Activity type', exact: true }).selectOption('Conversation Cards')
  await page.getByRole('link', { name: new RegExp(matching.title) }).click()
  await expect(page.getByRole('heading', { name: matching.title, exact: true })).toBeVisible()
  await expect(page.getByText(matching.prompt, { exact: true })).toBeVisible()

  await page.getByRole('link', { name: 'Surprise Me', exact: true }).click()
  await page.getByRole('combobox', { name: 'Level (required)', exact: true }).selectOption('A2')
  await page.getByRole('combobox', { name: 'Activity type (optional)', exact: true }).selectOption('Role-play Scenarios')
  const randomResponse = page.waitForResponse((response) => response.url().includes('/api/random-activities/next?') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Surprise Me', exact: true }).click()
  const selected = (await (await randomResponse).json()).activity
  expect(selected.level).toBe('A2')
  expect(selected.type).toBe('Role-play')
  await expect(page.getByRole('heading', { name: selected.title, exact: true })).toBeVisible()
  const addFavorite = page.getByRole('button', { name: /^Add to Favorites/ })
  const removeFavorite = page.getByRole('button', { name: /^Remove from Favorites/ })
  await expect(addFavorite.or(removeFavorite)).toBeEnabled()
  if (await addFavorite.count()) await addFavorite.click()
  await expect(removeFavorite).toBeEnabled()
  await page.getByRole('link', { name: 'Favorites', exact: true }).click()
  await expect(page.getByRole('list', { name: 'Favorite activities' }).getByRole('link', { name: new RegExp(selected.title) })).toBeVisible()

  await page.getByRole('link', { name: 'My Activities', exact: true }).click()
  const title = `E2E ${testInfo.project.name} ${Date.now()}`
  const prompt = 'Explain a useful skill.\nGive an example from your life.'
  await page.getByLabel('Title', { exact: true }).fill(title)
  await page.getByRole('combobox', { name: 'Level', exact: true }).selectOption('B2')
  await page.getByRole('combobox', { name: 'Topic', exact: true }).selectOption('Work')
  await page.getByRole('combobox', { name: 'Activity type', exact: true }).selectOption('Conversation Card')
  await page.getByLabel('Speaking prompt', { exact: true }).fill(prompt)
  await page.getByLabel('Follow-up questions (optional)').fill('How did you learn it?')
  await page.getByRole('button', { name: 'Create activity', exact: true }).click()
  await expect(page.getByText('Activity saved. Find it below or in Library.')).toBeVisible()
  await expect(page.getByRole('list', { name: 'Your custom activities' }).getByRole('link', { name: new RegExp(title) })).toBeVisible()
  await page.getByRole('link', { name: 'Library', exact: true }).click()
  await page.getByRole('link', { name: new RegExp(title) }).click()
  await expect(page.getByText(prompt, { exact: true })).toBeVisible()
  const source = page.url()
  await page.getByRole('button', { name: 'Enter Focus Mode', exact: true }).click()
  const focus = page.getByRole('main', { name: 'Focus Mode', exact: true })
  await expect(focus.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await expect(focus.getByText(prompt, { exact: true })).toBeVisible()
  await expect(page.getByRole('navigation')).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Exit Focus Mode', exact: true }).click()
  await expect(page).toHaveURL(source)
  await expect(page.getByRole('button', { name: 'Enter Focus Mode', exact: true })).toBeFocused()
  await expect(page.getByText(prompt, { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await expect(page.getByText('How did you learn it?', { exact: true })).toBeVisible()
})
